"""Compose synchronized Blender POV/follow frames into one traceable MP4."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import imageio_ffmpeg
from PIL import Image, ImageDraw

from .sweep_video import _font

SIZE = (1920, 1080)
FPS = 18
RUN_SECONDS = 5
CARD_SECONDS = 3
BG = "#10191e"
TEXT = "#eef0e9"
MUTED = "#a7b3b8"
ACCENT = "#79c8b3"
CAUTION = "#eab28a"
FONTS = {size: _font(size) for size in (22,24,26,28,30,32,42,48,54,64,96)}


def text(draw, position, value, size=28, color=TEXT):
    draw.text(position,value,font=FONTS[size],fill=color)


def status(run: dict) -> tuple[str, str]:
    if run['outcome'] == 'route_blocked':
        return 'Route blocked for this body envelope',CAUTION
    gap = run['reach_distance']-run['profile']['arm_length']
    if abs(gap) <= .05:
        return 'Near reach limit; needs measurement',CAUTION
    if gap > 0:
        return 'Target is outside this reach envelope',CAUTION
    return 'Route and reach envelope fit',ACCENT


def compose(report: dict, directory: Path, frame_index: int) -> Image.Image:
    index = frame_index // (FPS*RUN_SECONDS)
    run = report['recorded_runs'][index]
    image = Image.new('RGB',SIZE,BG)
    draw = ImageDraw.Draw(image)
    text(draw,(24,23),'Bread test',30,ACCENT)
    text(draw,(24,68),run['task']['title'],48)
    text(draw,(1450,27),f"Run {index+1:02d} of {len(report['recorded_runs'])}",32)
    text(draw,(1450,77),f"Evaluation {run['evaluation']:,}",26,MUTED)
    text(draw,(24,147),'Eye-level POV',28)
    text(draw,(968,147),'Third-person follow with camera cutaway',28)
    for view,x in (('pov',24),('third-person',968)):
        with Image.open(directory/view/f'{frame_index:05d}.png') as source:
            if source.size != (928,730):
                raise ValueError('Unexpected camera resolution')
            image.paste(source,(x,192))
    message,color = status(run)
    text(draw,(24,950),message,30,color)
    text(draw,(1120,949),f"Reach {run['reach_distance']*100:.1f} cm",26)
    text(draw,(1510,949),f"Model limit {run['profile']['arm_length']*100:.0f} cm",26)
    text(draw,(24,1007),'Actual LiDAR scan. Hypothetical props. Hand motion is illustrative.',24,MUTED)
    text(draw,(24,1043),'Time-compressed playback. Navigation and reach screening; grasp and device operation are untested.',22,MUTED)
    return image


def card(report: dict, directory: Path, ending: bool = False) -> Image.Image:
    image = Image.new('RGB',SIZE,BG)
    draw = ImageDraw.Draw(image)
    text(draw,(64,65),'Bread test',48,ACCENT)
    text(draw,(64,192),f"{report['evaluations']:,}",96)
    text(draw,(64,322),'distinct scenarios in one scanned room',42)
    text(draw,(64,440),'10 everyday tasks generated by Astra',32)
    text(draw,(64,506),'TypeSafe chose the next task to investigate',32)
    text(draw,(64,572),'Four body profiles and 25 target placements',32)
    text(draw,(64,680),'Two synchronized camera views',42,ACCENT)
    text(draw,(64,750),'Eye-level POV and third-person follow',30,MUTED)
    text(draw,(64,820),'Saved paths replayed against the captured 3D mesh',26,MUTED)
    with Image.open(directory/'third-person'/'00085.png') as preview:
        image.paste(preview.resize((880,692)),(1000,185))
    note = 'All ten filmed routes agree with an independent BFS check.' if ending else 'Medicine, computer use, drinks, books, phones and other table tasks.'
    text(draw,(64,935),note,30)
    text(draw,(64,1004),'Props and body profiles are simulation assumptions. This does not establish physical task ability or ADA compliance.',24,MUTED)
    text(draw,(64,1044),f"Scan {report['scan_id']}   Seed {report['seed']}",22,MUTED)
    return image


def render(report_path: Path, directory: Path, output: Path) -> dict:
    report = json.loads(report_path.read_text())
    if not report['complete']:
        raise ValueError('Campaign has not completed')
    count = len(report['recorded_runs'])*FPS*RUN_SECONDS
    for view in ('pov','third-person'):
        missing = [index for index in range(count) if not (directory/view/f'{index:05d}.png').is_file()]
        if missing:
            raise ValueError(f'{view} is missing {len(missing)} frames')
    writer = imageio_ffmpeg.write_frames(str(output),SIZE,fps=FPS,codec='libx264',
        pix_fmt_out='yuv420p',quality=8,macro_block_size=1,output_params=['-movflags','+faststart'])
    writer.send(None)
    try:
        intro = card(report,directory).tobytes()
        for _ in range(CARD_SECONDS*FPS):
            writer.send(intro)
        for index in range(count):
            frame = compose(report,directory,index)
            writer.send(frame.tobytes())
        ending = card(report,directory,ending=True).tobytes()
        for _ in range(CARD_SECONDS*FPS):
            writer.send(ending)
    finally:
        writer.close()
    compose(report,directory,85).save(output.with_suffix('.png'))
    manifest = {'video':str(output.resolve()),'report':str(report_path.resolve()),
                'report_sha256':hashlib.sha256(report_path.read_bytes()).hexdigest(),
                'graph_hash':report['graph_hash'],'source_files':report['sources'],
                'fps':FPS,'width':SIZE[0],'height':SIZE[1],
                'duration_seconds':2*CARD_SECONDS+len(report['recorded_runs'])*RUN_SECONDS,
                'cameras':['eye-level POV','third-person follow with camera cutaway'],
                'selection':'One wheelchair example per task; deliberately includes fits and near-limit reach attempts, not a representative sample.',
                'chapters':[{'seconds':CARD_SECONDS+index*RUN_SECONDS,'task':run['task']['title'],
                             'evaluation':run['evaluation'],'outcome':run['outcome']}
                            for index,run in enumerate(report['recorded_runs'])]}
    output.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n')
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--campaign',type=Path,required=True)
    parser.add_argument('--frames',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    args = parser.parse_args()
    print(json.dumps(render(args.campaign,args.frames,args.out),indent=2))


if __name__ == '__main__':
    main()
